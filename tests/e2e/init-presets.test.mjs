// @ts-check
/**
 * @fileoverview E2E tests for the init presets, flags, and sync reuse of saved choices.
 */

import { describe, it, before, after } from "node:test";
import assert from "node:assert/strict";
import { execFile } from "node:child_process";
import fs from "node:fs";
import path from "node:path";
import os from "node:os";
import { promisify } from "node:util";
import { parse as parseYaml } from "yaml";
import { ConflictManager } from "../../dist/adapters/conflict-manager.js";

const execFileAsync = promisify(execFile);
const CLI_PATH = path.resolve("bin", "sauron.mjs");

describe("E2E: init presets and flags", () => {
  /** @type {string} */
  let dir;
  /** @param {string} rel */
  const exists = (rel) => fs.existsSync(path.join(dir, rel));

  before(() => {
    dir = fs.mkdtempSync(path.join(os.tmpdir(), "sauron-e2e-preset-"));
  });

  after(() => {
    fs.rmSync(dir, { recursive: true, force: true });
  });

  it("Recommended preset installs Claude Code natively plus the shared core", async () => {
    await execFileAsync("node", [CLI_PATH, "init", "--yes"], {
      cwd: dir,
      maxBuffer: 16 * 1024 * 1024,
    });

    for (const rel of [
      "AGENTS.md",
      ".agents/anti-patterns.md",
      "CLAUDE.md",
      ".claude/settings.json",
      ".claude/output-styles/caveman.md",
      ".claude/agents/gandalf.md",
      ".claude/agents/frodo.md",
      ".claude/commands/gandalf.md",
      ".agents/skills/plan-feature/SKILL.md",
      ".claude/skills/plan-feature/SKILL.md",
    ]) {
      assert.ok(exists(rel), `missing ${rel}`);
    }
    assert.ok(
      !exists(".cursor"),
      "Cursor must not be generated by the Recommended preset",
    );
    assert.ok(
      !exists(".claude/agents/architect.md"),
      "core agents are not part of Recommended",
    );

    const agent = fs.readFileSync(
      path.join(dir, ".claude/agents/gandalf.md"),
      "utf8",
    );
    assert.match(agent, /^---\nname: gandalf\ndescription: "/);

    const skill = fs.readFileSync(
      path.join(dir, ".claude/skills/plan-feature/SKILL.md"),
      "utf8",
    );
    assert.ok(
      skill.startsWith("---"),
      "skills are copied verbatim, frontmatter first",
    );
    assert.ok(!skill.includes("sauron:start"), "skills carry no managed block");

    const config = fs.readFileSync(
      path.join(dir, "sauron.config.yaml"),
      "utf8",
    );
    const saved = parseYaml(config);
    assert.equal(saved.version, "2.0.0");
    assert.equal(saved.runtimes.claude, true);
    assert.equal(saved.runtimes.cursor, false);
    assert.equal(saved.skills, "all");
    assert.equal(saved.init.agents, "fellowship");
    assert.equal(saved.init.commands, true);
    assert.ok(!("runtimes" in saved.init));
  });

  it("sync reuses the saved choices and keeps user-edited skills", async () => {
    const skillPath = path.join(dir, ".claude/skills/plan-feature/SKILL.md");
    fs.appendFileSync(skillPath, "\nMy local tweak.\n");
    const { stdout } = await execFileAsync("node", [CLI_PATH, "sync"], {
      cwd: dir,
      maxBuffer: 16 * 1024 * 1024,
    });
    assert.ok(
      !exists(".cursor"),
      "sync must not add runtimes that were not chosen",
    );
    assert.match(fs.readFileSync(skillPath, "utf8"), /My local tweak\./);
    assert.match(stdout, /SKIPPED.*\.claude\/skills\/plan-feature\/SKILL\.md/);
  });

  it("CLAUDE.md lists only the subagents and commands that were installed", async () => {
    const other = fs.mkdtempSync(
      path.join(os.tmpdir(), "sauron-e2e-noagents-"),
    );
    try {
      await execFileAsync(
        "node",
        [
          CLI_PATH,
          "init",
          "--yes",
          "--runtimes=claude",
          "--agents=none",
          "--skills=none",
          "--no-commands",
        ],
        { cwd: other },
      );
      const claudeMd = fs.readFileSync(path.join(other, "CLAUDE.md"), "utf8");
      assert.doesNotMatch(claudeMd, /\/gandalf/);
      assert.match(claudeMd, /Not installed in this project/);
    } finally {
      fs.rmSync(other, { recursive: true, force: true });
    }
  });

  it("add copies a skill to .claude/skills too and keeps edited files", async () => {
    const other = fs.mkdtempSync(path.join(os.tmpdir(), "sauron-e2e-add-"));
    try {
      await execFileAsync(
        "node",
        [CLI_PATH, "init", "--yes", "--runtimes=claude", "--skills=none"],
        { cwd: other },
      );
      await execFileAsync("node", [CLI_PATH, "add", "plan-feature"], {
        cwd: other,
      });
      const claudeSkill = path.join(
        other,
        ".claude/skills/plan-feature/SKILL.md",
      );
      assert.ok(
        fs.existsSync(path.join(other, ".agents/skills/plan-feature/SKILL.md")),
      );
      assert.ok(fs.existsSync(claudeSkill));
      fs.appendFileSync(claudeSkill, "\nMine.\n");
      const { stdout } = await execFileAsync(
        "node",
        [CLI_PATH, "add", "plan-feature"],
        { cwd: other },
      );
      assert.match(stdout, /PARTIAL/);
      assert.match(fs.readFileSync(claudeSkill, "utf8"), /Mine\./);
    } finally {
      fs.rmSync(other, { recursive: true, force: true });
    }
  });

  it("installs native subagents and commands for OpenCode and omp", async () => {
    const other = fs.mkdtempSync(path.join(os.tmpdir(), "sauron-e2e-native-"));
    try {
      const { stdout } = await execFileAsync(
        "node",
        [CLI_PATH, "init", "--yes", "--runtimes=opencode,omp", "--skills=none"],
        { cwd: other, maxBuffer: 16 * 1024 * 1024 },
      );
      assert.match(
        stdout,
        /9 into \.opencode\/agents\/, 9 into \.omp\/agents\//,
      );
      /** @param {string} rel */
      const count = (rel) =>
        fs.readdirSync(path.join(other, rel)).length;
      assert.equal(count(".opencode/agents"), 9);
      assert.equal(count(".opencode/commands"), 123);
      assert.equal(count(".omp/agents"), 9);
      assert.equal(count(".omp/prompts"), 119);
      assert.ok(
        !fs.existsSync(path.join(other, ".claude")),
        "Claude Code was not selected",
      );

      const config = fs.readFileSync(
        path.join(other, "sauron.config.yaml"),
        "utf8",
      );
      assert.deepEqual(parseYaml(config).init.nativeRuntimes, ["opencode", "omp"]);

      const agent = path.join(other, ".opencode/agents/frodo.md");
      fs.appendFileSync(agent, "\nMy local tweak.\n");
      const sync = await execFileAsync("node", [CLI_PATH, "sync"], {
        cwd: other,
        maxBuffer: 16 * 1024 * 1024,
      });
      assert.match(sync.stdout, /SKIPPED.*\.opencode\/agents\/frodo\.md/);
      assert.match(fs.readFileSync(agent, "utf8"), /My local tweak\./);
    } finally {
      fs.rmSync(other, { recursive: true, force: true });
    }
  });

  it("sync on a config saved before 3.2.0 adds no OpenCode or omp assets", async () => {
    const other = fs.mkdtempSync(path.join(os.tmpdir(), "sauron-e2e-legacy-"));
    try {
      fs.writeFileSync(
        path.join(other, "sauron.config.yaml"),
        "init:\n  runtimes: [opencode, omp]\n  agents: fellowship\n  skills: none\n  commands: true\n",
      );
      await execFileAsync("node", [CLI_PATH, "upgrade"], { cwd: other });
      await execFileAsync("node", [CLI_PATH, "sync"], {
        cwd: other,
        maxBuffer: 16 * 1024 * 1024,
      });
      for (const rel of [
        ".opencode/agents",
        ".opencode/commands",
        ".omp/agents",
        ".omp/prompts",
      ]) {
        assert.ok(!fs.existsSync(path.join(other, rel)), `${rel} must not exist`);
      }
    } finally {
      fs.rmSync(other, { recursive: true, force: true });
    }
  });

  it("sync removes old scanned-folder READMEs but keeps edited ones", async () => {
    const other = fs.mkdtempSync(path.join(os.tmpdir(), "sauron-e2e-readme-"));
    try {
      fs.writeFileSync(
        path.join(other, "sauron.config.yaml"),
        "init:\n  runtimes: [opencode]\n  agents: none\n  skills: none\n  commands: false\n",
      );
      await execFileAsync("node", [CLI_PATH, "upgrade"], { cwd: other });
      const manager = new ConflictManager(other);
      manager.safeWrite(".opencode/agents/README.md", "# Old note", "opencode");
      manager.safeWrite(".opencode/commands/README.md", "# Old note", "opencode");
      const edited = path.join(other, ".opencode/commands/README.md");
      fs.appendFileSync(edited, "\nMine.\n");

      const { stdout } = await execFileAsync("node", [CLI_PATH, "sync"], { cwd: other });
      assert.match(stdout, /REMOVED.*\.opencode\/agents\/README\.md/);
      assert.match(stdout, /SKIPPED.*\.opencode\/commands\/README\.md/);
      assert.ok(!fs.existsSync(path.join(other, ".opencode/agents/README.md")));
      assert.match(fs.readFileSync(edited, "utf8"), /Mine\./);
      assert.ok(fs.existsSync(path.join(other, ".opencode/README.md")));
    } finally {
      fs.rmSync(other, { recursive: true, force: true });
    }
  });

  it("sync installs command aliases and retires only unchanged legacy wrappers", async () => {
    const other = fs.mkdtempSync(path.join(os.tmpdir(), "sauron-e2e-alias-"));
    try {
      await execFileAsync("node", [CLI_PATH, "init", "--yes", "--skills=workflow"], { cwd: other, maxBuffer: 16 * 1024 * 1024 });
      const manager = new ConflictManager(other);
      manager.safeWrite(".claude/commands/caveman.md", "# Old command", "install", false, { raw: true });
      manager.safeWrite(".claude/commands/handoff.md", "# Old command", "install", false, { raw: true });
      fs.appendFileSync(path.join(other, ".claude/commands/handoff.md"), "\nMy edit.\n");
      await execFileAsync("node", [CLI_PATH, "sync"], { cwd: other, maxBuffer: 16 * 1024 * 1024 });
      assert.ok(!fs.existsSync(path.join(other, ".claude/commands/caveman.md")));
      assert.match(fs.readFileSync(path.join(other, ".claude/commands/handoff.md"), "utf8"), /My edit/);
      assert.match(fs.readFileSync(path.join(other, ".claude/commands/sauron-caveman.md"), "utf8"), /\/sauron-caveman/);
      assert.ok(fs.existsSync(path.join(other, ".claude/skills/caveman/SKILL.md")));
      fs.writeFileSync(path.join(other, ".claude/commands/sauron-caveman.md"), "# User alias\n");
      manager.safeWrite(".claude/commands/caveman.md", "# Old command", "install", false, { raw: true });
      await execFileAsync("node", [CLI_PATH, "sync"], { cwd: other, maxBuffer: 16 * 1024 * 1024 });
      assert.ok(fs.existsSync(path.join(other, ".claude/commands/caveman.md")), "keep the old wrapper when the replacement cannot install");
      assert.equal(fs.readFileSync(path.join(other, ".claude/commands/sauron-caveman.md"), "utf8"), "# User alias\n");
    } finally {
      fs.rmSync(other, { recursive: true, force: true });
    }
  });

  it("rejects an unknown runtime with exit code 1", async () => {
    await assert.rejects(
      execFileAsync(
        "node",
        [CLI_PATH, "init", "--yes", "--runtimes=claude,nope"],
        { cwd: dir },
      ),
      (error) => {
        const e = /** @type {{ code: number, stderr: string }} */ (error);
        assert.equal(e.code, 1);
        assert.match(e.stderr, /Unknown runtime 'nope'/);
        return true;
      },
    );
  });
});

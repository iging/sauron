// @ts-check
/**
 * @fileoverview E2E tests for the init presets, flags, and sync reuse of saved choices.
 */

import { describe, it, before, after } from "node:test";
import assert from "node:assert/strict";
import { execFile } from "node:child_process";
import fs from "node:fs";
import path from "node:path";
import os from "node:os";
import { promisify } from "node:util";

const execFileAsync = promisify(execFile);
const CLI_PATH = path.resolve("bin", "sauron.mjs");

describe("E2E: init presets and flags", () => {
  /** @type {string} */
  let dir;
  /** @param {string} rel */
  const exists = (rel) => fs.existsSync(path.join(dir, rel));

  before(() => {
    dir = fs.mkdtempSync(path.join(os.tmpdir(), "sauron-e2e-preset-"));
  });

  after(() => {
    fs.rmSync(dir, { recursive: true, force: true });
  });

  it("Recommended preset installs Claude Code natively plus the shared core", async () => {
    await execFileAsync("node", [CLI_PATH, "init", "--yes"], { cwd: dir, maxBuffer: 16 * 1024 * 1024 });

    for (const rel of [
      "AGENTS.md",
      ".agents/anti-patterns.md",
      "CLAUDE.md",
      ".claude/settings.json",
      ".claude/output-styles/caveman.md",
      ".claude/agents/gandalf.md",
      ".claude/agents/frodo.md",
      ".claude/commands/gandalf.md",
      ".agents/skills/plan-feature/SKILL.md",
      ".claude/skills/plan-feature/SKILL.md",
    ]) {
      assert.ok(exists(rel), `missing ${rel}`);
    }
    assert.ok(!exists(".cursor"), "Cursor must not be generated by the Recommended preset");
    assert.ok(!exists(".claude/agents/architect.md"), "core agents are not part of Recommended");

    const agent = fs.readFileSync(path.join(dir, ".claude/agents/gandalf.md"), "utf8");
    assert.match(agent, /^---\nname: gandalf\ndescription: "/);

    const skill = fs.readFileSync(path.join(dir, ".claude/skills/plan-feature/SKILL.md"), "utf8");
    assert.ok(skill.startsWith("---"), "skills are copied verbatim, frontmatter first");
    assert.ok(!skill.includes("sauron:start"), "skills carry no managed block");

    const config = fs.readFileSync(path.join(dir, "sauron.config.yaml"), "utf8");
    assert.match(config, /^init:\n  runtimes: \[claude\]\n  agents: fellowship\n  skills: all\n  commands: true/m);
  });

  it("sync reuses the saved choices and keeps user-edited skills", async () => {
    const skillPath = path.join(dir, ".claude/skills/plan-feature/SKILL.md");
    fs.appendFileSync(skillPath, "\nMy local tweak.\n");
    const { stdout } = await execFileAsync("node", [CLI_PATH, "sync"], { cwd: dir, maxBuffer: 16 * 1024 * 1024 });
    assert.ok(!exists(".cursor"), "sync must not add runtimes that were not chosen");
    assert.match(fs.readFileSync(skillPath, "utf8"), /My local tweak\./);
    assert.match(stdout, /SKIPPED.*\.claude\/skills\/plan-feature\/SKILL\.md/);
  });

  it("rejects an unknown runtime with exit code 1", async () => {
    await assert.rejects(
      execFileAsync("node", [CLI_PATH, "init", "--yes", "--runtimes=claude,nope"], { cwd: dir }),
      (error) => {
        const e = /** @type {{ code: number, stderr: string }} */ (error);
        assert.equal(e.code, 1);
        assert.match(e.stderr, /Unknown runtime 'nope'/);
        return true;
      },
    );
  });
});

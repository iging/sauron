/**
 * @fileoverview Cline adapter generating the official .cline/ project scaffold
 * (rules, workflows, skills, hooks). See https://docs.cline.bot/features/cline-rules
 */

import {
  formatCavemanSection,
  type RuntimeAdapter,
  type TranspileContext,
  type TranspileOutput,
} from "./types.js";

const DOCS_URL = "https://docs.cline.bot/features/cline-rules";
const RULES_PATH = ".cline/rules/sauron.md";

const ROOT_README = `# .cline/

Cline project scaffold generated by Sauron. Docs: ${DOCS_URL}

| Folder | Purpose |
| --- | --- |
| \`rules/\` | Workspace rules (Markdown). Every \`.md\` file is loaded into Cline's system prompt. |
| \`workflows/\` | Reusable task workflows, invoked in chat as \`/<filename>.md\`. |
| \`skills/\` | Agent skills, one folder per skill containing a \`SKILL.md\`. |
| \`hooks/\` | Executable hook scripts that run on Cline lifecycle events. |

## Migration from \`.clinerules\`

Earlier Sauron versions wrote a single \`.clinerules\` file. Cline now treats
\`.clinerules/\` as a directory, and a file and directory cannot share that
name. To avoid failing on workspaces that still have the legacy file, Sauron
writes its rules to \`.cline/rules/sauron.md\`, which Cline also supports.

To migrate, move any custom content from the old \`.clinerules\` file into a
new file under \`.cline/rules/\` (for example \`.cline/rules/project.md\`) and
delete \`.clinerules\`. Do not keep the same rules in both places.
`;

const WORKFLOWS_README = `# .cline/workflows/

Scaffold folder generated by Sauron.

Workflows are Markdown files describing a repeatable sequence of steps.
Invoke one in Cline chat by typing \`/\` followed by its filename.

## Add a workflow

1. Create \`<name>.md\` in this folder (for example \`release.md\`).
2. Write a title, then numbered steps Cline should follow, including any
   commands to run or tools to use.
3. Run it with \`/release.md\`.

Docs: https://docs.cline.bot/features/slash-commands/workflows
`;

const SKILLS_README = `# .cline/skills/

Scaffold folder generated by Sauron.

Skills are on-demand capability packs. Cline reads each skill's name and
description and loads the full instructions only when relevant.

## Add a skill

1. Create a folder \`<skill-name>/\` here.
2. Add \`<skill-name>/SKILL.md\` with YAML frontmatter:

\`\`\`markdown
---
name: skill-name
description: One sentence on when to use this skill.
---

# Instructions
...
\`\`\`

3. Put any scripts or reference files next to \`SKILL.md\`.

Docs: https://docs.cline.bot/features/skills
`;

const HOOKS_README = `# .cline/hooks/

Scaffold folder generated by Sauron.

Hooks are executable scripts that Cline runs at lifecycle events (for
example before or after a tool call, or when a task starts). They receive a
JSON payload on stdin and can return JSON to allow, block, or annotate the
action.

## Add a hook

1. Create an executable script named after the event it handles
   (for example \`PreToolUse\`).
2. Read the JSON event from stdin and write a JSON response to stdout.
3. Make it executable (\`chmod +x\`) on macOS/Linux.

Docs: https://docs.cline.bot/features/hooks
`;

export class ClineAdapter implements RuntimeAdapter {
  public readonly id = "cline";
  public readonly name = "Cline";
  public readonly targetFiles = [
    RULES_PATH,
    ".cline/README.md",
    ".cline/workflows/README.md",
    ".cline/skills/README.md",
    ".cline/hooks/README.md",
  ];

  public transpile(context: TranspileContext): TranspileOutput[] {
    const lines: string[] = [];

    lines.push(`# Cline Rules for ${context.projectName}`);
    lines.push(`Sauron Autonomous Agent Protocol v${context.version}`);
    lines.push("");
    lines.push("## Autonomous Operating Directives");
    for (const rule of context.rules) {
      lines.push(`1. ${rule}`);
    }
    lines.push("");
    lines.push(...formatCavemanSection("##"));
    lines.push("## Fellowship Sub-Agents Delegation Model");
    for (const agent of context.fellowship) {
      lines.push(`- ${agent.name} (${agent.role}): ${agent.slashCommand}`);
      lines.push(
        `  Authority: can modify [${agent.authority.canModify.join(", ")}], must not modify [${agent.authority.mustNotModify.join(", ")}]`,
      );
    }
    lines.push("");
    lines.push("## Verification Gate Protocol");
    lines.push(
      "- Run tests and verify exit code 0 before marking any task complete.",
    );
    lines.push("- Never commit without passing linting and type checks.");
    lines.push("- Never expose credentials or secret keys.");
    lines.push("");
    lines.push("## Prohibited Anti-Patterns");
    for (const ap of context.antiPatterns) {
      lines.push(`- ${ap}`);
    }
    lines.push("");

    return [
      { relativePath: RULES_PATH, content: lines.join("\n"), format: "markdown" },
      { relativePath: ".cline/README.md", content: ROOT_README, format: "markdown" },
      {
        relativePath: ".cline/workflows/README.md",
        content: WORKFLOWS_README,
        format: "markdown",
      },
      {
        relativePath: ".cline/skills/README.md",
        content: SKILLS_README,
        format: "markdown",
      },
      {
        relativePath: ".cline/hooks/README.md",
        content: HOOKS_README,
        format: "markdown",
      },
    ];
  }
}

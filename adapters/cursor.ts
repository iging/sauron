/**
 * @fileoverview Cursor adapter generating the .cursor/ project scaffold (rules and skills).
 */

import {
  formatCavemanSection,
  type RuntimeAdapter,
  type TranspileContext,
  type TranspileOutput,
} from "./types.js";

export class CursorAdapter implements RuntimeAdapter {
  public readonly id = "cursor";
  public readonly name = "Cursor";
  public readonly targetFiles = [
    ".cursor/rules/sauron.mdc",
    ".cursor/README.md",
  ];
  public readonly retiredFiles = [
    ".cursor/rules/README.md",
    ".cursor/skills/README.md",
  ];

  public transpile(context: TranspileContext): TranspileOutput[] {
    const mdcLines: string[] = [];
    mdcLines.push("---");
    mdcLines.push(
      `description: Sauron unified governance rules for ${context.projectName}`,
    );
    mdcLines.push("globs:");
    mdcLines.push("alwaysApply: true");
    mdcLines.push("---");
    mdcLines.push("");
    mdcLines.push(`# Sauron Governance Rules for Cursor`);
    mdcLines.push("");
    mdcLines.push(`Managed by Sauron v${context.version}`);
    mdcLines.push("");
    mdcLines.push("## Operational Directives");
    mdcLines.push("");
    for (const rule of context.rules) {
      mdcLines.push(`- ${rule}`);
    }
    mdcLines.push("");
    mdcLines.push("## Fellowship Sub-Agents");
    mdcLines.push("");
    for (const agent of context.fellowship) {
      mdcLines.push(`- ${agent.name} (${agent.role}): ${agent.slashCommand}`);
    }
    mdcLines.push("");
    mdcLines.push("## Prohibited Anti-Patterns");
    mdcLines.push("");
    for (const ap of context.antiPatterns) {
      mdcLines.push(`- ${ap}`);
    }
    mdcLines.push("");
    mdcLines.push(...formatCavemanSection("##", context.cavemanMode));
    mdcLines.push("## Commands and Skills");
    mdcLines.push("");
    for (const skill of context.skills) {
      mdcLines.push(
        `- \`${skill.triggerCommand}\`: ${skill.name} (${skill.department})`,
      );
    }
    mdcLines.push("");

    // Keep setup notes outside the rule and skill discovery folders.
    const rulesReadme = [
      "## .cursor/rules",
      "",
      "Project rules for Cursor, managed by Sauron.",
      "",
      "## Adding a rule",
      "",
      "Create a `.cursor/rules/<name>.mdc` file. Each file starts with YAML frontmatter:",
      "",
      "```mdc",
      "---",
      "description: When this rule applies (used by the agent to decide relevance)",
      "globs: src/**/*.ts",
      "alwaysApply: false",
      "---",
      "",
      "Rule body in Markdown.",
      "```",
      "",
      "- `alwaysApply: true` includes the rule in every chat.",
      "- `globs` attaches the rule when matching files are referenced.",
      "- `description` alone lets the agent pull the rule in when relevant.",
      "",
      "`sauron.mdc` is generated by Sauron; edit `sauron.config.yaml` and re-run `sauron init` instead of editing it.",
      "The legacy root `.cursorrules` file is deprecated; use this folder.",
      "Cursor also reads `AGENTS.md` at the project root.",
      "",
      "Docs: https://cursor.com/docs/context/rules",
      "",
    ].join("\n");

    const skillsReadme = [
      "## .cursor/skills",
      "",
      "Agent Skills for Cursor.",
      "",
      "## Adding a skill",
      "",
      "Create `.cursor/skills/<skill-name>/` containing a `SKILL.md` file:",
      "",
      "```md",
      "---",
      "name: skill-name",
      "description: What the skill does and when to use it",
      "---",
      "",
      "Step-by-step instructions for the agent.",
      "```",
      "",
      "Cursor also discovers skills in `.agents/skills/`, which Sauron shares across runtimes.",
      "",
      "Docs: https://cursor.com/docs/skills",
      "",
    ].join("\n");

    return [
      {
        relativePath: ".cursor/rules/sauron.mdc",
        content: mdcLines.join("\n"),
        format: "markdown",
      },
      {
        relativePath: ".cursor/README.md",
        content: ["# Cursor", "", rulesReadme, skillsReadme].join("\n"),
        format: "markdown",
      },
    ];
  }
}

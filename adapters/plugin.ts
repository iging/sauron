/// <reference types="node" />
/**
 * @fileoverview Builds a Claude Code plugin and a local marketplace from the bundled catalog.
 * Format: https://code.claude.com/docs/en/plugins/manifest-reference.md
 * Returns file contents only. The CLI writes them through ConflictManager. No barrel files.
 */

import { buildInstallOutputs, type InstallOutput } from "./installer.js";
import type { InitPlan } from "./init-plan.js";

/** Plugin name. Claude Code namespaces its parts, for example `/sauron:gandalf`. */
export const PLUGIN_NAME = "sauron";

/** Marketplace name used for `/plugin install sauron@<marketplace>`. */
export const MARKETPLACE_NAME = "sauron-local";

/** Everything Sauron ships for Claude Code: both agent sets, all commands, all skills. */
const PLUGIN_PLAN: Readonly<InitPlan> = Object.freeze({
  runtimes: ["claude"],
  agents: "both",
  skills: "all",
  caveman: "full",
  commands: true,
  nativeRuntimes: ["claude"],
});

/** Maps a Claude Code project path to its place inside the plugin. */
const PLUGIN_FOLDERS: readonly (readonly [string, string])[] = [
  [".claude/agents/", "agents/"],
  [".claude/commands/", "commands/"],
  [".claude/skills/", "skills/"],
];

/**
 * Adds a `description` frontmatter block to a command file that has none, so Claude Code can
 * list it. The description comes from the first heading, or the file name.
 */
function withDescription(content: string, relativePath: string): string {
  if (/^---\r?\n/.test(content)) return content;
  const heading = /^#\s+(.+)$/m.exec(content)?.[1]?.trim();
  const name = relativePath.split("/").pop()?.replace(/\.md$/, "") ?? "command";
  const description = (heading ?? name).replace(/`/g, "");
  return `---\ndescription: ${JSON.stringify(description)}\n---\n\n${content}`;
}

/**
 * Builds the plugin files and a marketplace that points at them.
 *
 * Layout under the output folder:
 * - `.claude-plugin/marketplace.json`
 * - `sauron/.claude-plugin/plugin.json`
 * - `sauron/agents/*.md`, `sauron/commands/*.md`, `sauron/skills/<name>/SKILL.md`
 *
 * @param sauronRoot - Root of the Sauron package.
 * @param version - Package version, written into the manifest.
 * @returns Files relative to the output folder.
 */
export function buildClaudePlugin(
  sauronRoot: string,
  version: string,
): InstallOutput[] {
  const files: InstallOutput[] = [];
  for (const output of buildInstallOutputs(sauronRoot, PLUGIN_PLAN)) {
    const folder = PLUGIN_FOLDERS.find(([from]) =>
      output.relativePath.startsWith(from),
    );
    if (!folder) continue;
    const relativePath = `${PLUGIN_NAME}/${folder[1]}${output.relativePath.slice(folder[0].length)}`;
    files.push({
      relativePath,
      content:
        folder[1] === "commands/"
          ? withDescription(output.content, relativePath)
          : output.content,
      raw: true,
    });
  }
  const manifest = {
    name: PLUGIN_NAME,
    version,
    description:
      "Sauron Fellowship agents, slash commands, and skills for Claude Code.",
    author: { name: "Sauron contributors" },
    homepage: "https://sauron-cli.vercel.app",
    repository: "https://github.com/iging/sauron",
    license: "MIT OR Apache-2.0 OR Unlicense",
  };
  const marketplace = {
    name: MARKETPLACE_NAME,
    description: "Local marketplace generated by `sauron plugin`.",
    owner: { name: "Sauron contributors" },
    plugins: [
      {
        name: PLUGIN_NAME,
        source: `./${PLUGIN_NAME}`,
        description: manifest.description,
      },
    ],
  };
  const readme = [
    "# Sauron for Claude Code",
    "",
    "Sauron Fellowship agents, slash commands, and skills packaged as one Claude Code plugin.",
    "",
    "- Agents: call them as `@agent-sauron:<name>`, for example `@agent-sauron:gandalf`.",
    "- Commands: run them as `/sauron:<name>`, for example `/sauron:gandalf <goal>`.",
    "- Skills: Claude loads them when a task matches, or run `/sauron:<skill>`.",
    "",
    "Install from the folder that holds `.claude-plugin/marketplace.json`:",
    "",
    "```text",
    `/plugin marketplace add ./<folder>`,
    `/plugin install ${PLUGIN_NAME}@${MARKETPLACE_NAME}`,
    "```",
    "",
    "Generated by `sauron plugin`. Rebuild it after updating Sauron. Files you changed are kept.",
    "",
  ].join("\n");
  files.push(
    {
      relativePath: `${PLUGIN_NAME}/README.md`,
      content: readme,
      raw: true,
    },
    {
      relativePath: `${PLUGIN_NAME}/.claude-plugin/plugin.json`,
      content: `${JSON.stringify(manifest, null, 2)}\n`,
      raw: true,
    },
    {
      relativePath: ".claude-plugin/marketplace.json",
      content: `${JSON.stringify(marketplace, null, 2)}\n`,
      raw: true,
    },
  );
  return files.sort((a, b) => a.relativePath.localeCompare(b.relativePath));
}

/**
 * @fileoverview Windsurf (Devin Desktop) adapter generating the `.windsurf/`
 * workspace scaffold: an always-on rule plus workflow and skill folder READMEs.
 * @see https://docs.devin.ai/desktop/cascade/memories
 */

import {
  formatCavemanSection,
  type RuntimeAdapter,
  type TranspileContext,
  type TranspileOutput,
} from "./types.js";

/** Windsurf ignores workspace rule content beyond this many characters. */
export const WINDSURF_RULE_CHAR_LIMIT = 12000;

const RULE_PATH = ".windsurf/rules/sauron.md";
const WORKFLOWS_README = ".windsurf/workflows/README.md";
const SKILLS_README = ".windsurf/skills/README.md";
const DOC_URL = "https://docs.devin.ai/desktop/cascade/memories";
const TRUNCATED_NOTE =
  "- (catalog truncated to fit the 12000 character rule limit)";

export class WindsurfAdapter implements RuntimeAdapter {
  public readonly id = "windsurf";
  public readonly name = "Windsurf";
  public readonly targetFiles = [RULE_PATH, WORKFLOWS_README, SKILLS_README];

  public transpile(context: TranspileContext): TranspileOutput[] {
    return [
      {
        relativePath: RULE_PATH,
        content: buildRule(context),
        format: "markdown",
      },
      {
        relativePath: WORKFLOWS_README,
        content: folderReadme(
          "Workflows",
          "Workflows are reusable Markdown prompts that Cascade runs as `/<workflow-name>` slash commands.",
          [
            "1. Create `<workflow-name>.md` in this folder.",
            "2. Write a title, a short description, and numbered steps for Cascade to follow.",
            "3. Invoke it in Cascade with `/<workflow-name>`.",
          ],
          ".devin/workflows/",
        ),
        format: "markdown",
      },
      {
        relativePath: SKILLS_README,
        content: folderReadme(
          "Skills",
          "Skills are folders that bundle instructions and supporting files Cascade can load on demand.",
          [
            "1. Create `<skill-name>/SKILL.md` in this folder.",
            "2. Start `SKILL.md` with frontmatter holding `name` and `description`, then the instructions.",
            "3. Put any scripts or reference files next to `SKILL.md`.",
          ],
          ".devin/skills/",
        ),
        format: "markdown",
      },
    ];
  }
}

function buildRule(context: TranspileContext): string {
  const out: string[] = [
    "---",
    "trigger: always_on",
    "---",
    "",
    `# Sauron Rules : ${context.projectName}`,
    `Generated by Sauron v${context.version}`,
    "",
    "## Character and Persona",
    "Operate as a senior polyglot software engineer strictly adhering to Sauron governance.",
    "",
    "## Architectural Constraints",
    ...context.rules.map((rule) => `- ${rule}`),
    "",
    ...formatCavemanSection("##", context.cavemanMode),
    "## Fellowship Sub-Agents Execution Hierarchy",
    ...context.fellowship.map(
      (a) => `- ${a.name} [${a.role}] : invoke with ${a.slashCommand}`,
    ),
    "",
    "## Blocked Anti-Patterns",
    ...context.antiPatterns.map((ap) => `- ${ap}`),
    "",
    "## Skills Catalog",
  ];
  // Reserve room for the truncation note plus trailing newlines.
  const budget = WINDSURF_RULE_CHAR_LIMIT - TRUNCATED_NOTE.length - 2;
  let length = out.join("\n").length;
  for (const skill of context.skills) {
    const line = `- ${skill.triggerCommand} -> ${skill.name}`;
    if (length + 1 + line.length > budget) {
      out.push(TRUNCATED_NOTE);
      break;
    }
    out.push(line);
    length += 1 + line.length;
  }
  out.push("");
  const content = out.join("\n");
  if (content.length > WINDSURF_RULE_CHAR_LIMIT) {
    throw new Error(
      `Windsurf rule exceeds ${WINDSURF_RULE_CHAR_LIMIT} chars (${content.length}); reduce rules or anti-patterns.`,
    );
  }
  return content;
}

function folderReadme(
  kind: string,
  purpose: string,
  steps: readonly string[],
  devinPath: string,
): string {
  return [
    `# Windsurf ${kind} (managed by Sauron)`,
    "",
    purpose,
    "",
    `## Add ${kind.toLowerCase()}`,
    ...steps,
    "",
    "## Note: `.devin/` is preferred",
    "Windsurf is now Devin Desktop. `.windsurf/` is still read, but the newer preferred",
    `location is \`${devinPath}\`. Move files there once your team has upgraded.`,
    "",
    `Docs: ${DOC_URL}`,
    "",
  ].join("\n");
}

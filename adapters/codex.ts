/**
 * @fileoverview Codex adapter generating the `.codex/` project scaffold:
 * a commented `config.toml` template and a README explaining that Codex
 * reads `AGENTS.md` and `.agents/skills` for instructions.
 */

import {
  formatCavemanSection,
  type RuntimeAdapter,
  type TranspileContext,
  type TranspileOutput,
} from "./types.js";

const AGENTS_MD_DOC_URL =
  "https://learn.chatgpt.com/docs/agent-configuration/agents-md";

export class CodexAdapter implements RuntimeAdapter {
  public readonly id = "codex";
  public readonly name = "Codex";
  public readonly targetFiles = [".codex/config.toml", ".codex/README.md"];

  public transpile(context: TranspileContext): TranspileOutput[] {
    return [
      {
        relativePath: ".codex/config.toml",
        content: this.buildConfig(context),
        format: "text",
      },
      {
        relativePath: ".codex/README.md",
        content: this.buildReadme(context),
        format: "markdown",
      },
    ];
  }

  private buildConfig(context: TranspileContext): string {
    return [
      `# Codex project configuration for ${context.projectName}`,
      `# Generated by Sauron v${context.version}`,
      "# Unverified template: confirm keys against the official Codex docs.",
      "# Uncomment and edit the settings you need.",
      "",
      '# model = "gpt-5-codex"',
      '# sandbox_mode = "workspace-write"   # read-only | workspace-write | danger-full-access',
      '# approval_policy = "on-request"     # untrusted | on-failure | on-request | never',
      "",
      "# [mcp_servers.example]",
      '# command = "npx"',
      '# args = ["-y", "example-mcp-server"]',
      "",
    ].join("\n");
  }

  private buildReadme(context: TranspileContext): string {
    const lines: string[] = [];
    lines.push(`# .codex/ for ${context.projectName}`);
    lines.push(`Generated by Sauron v${context.version}`);
    lines.push("");
    lines.push("## Purpose");
    lines.push(
      "Codex reads project instructions from `AGENTS.md` at the repository root " +
        "(and nested `AGENTS.md` files in subdirectories). Put coding rules there, not in this folder.",
    );
    lines.push(`Official doc: ${AGENTS_MD_DOC_URL}`);
    lines.push("");
    lines.push("## Files");
    lines.push(
      "- `config.toml`: project-scoped Codex settings (model, sandbox, approval policy, `[mcp_servers]`). All keys ship commented out.",
    );
    lines.push(
      "<!-- unverified: config.toml key names and project-scoped loading from Codex CLI public docs; not confirmed on the AGENTS.md doc page -->",
    );
    lines.push("");
    lines.push("## Skills");
    lines.push(
      "Codex discovers skills in `.agents/skills/<name>/SKILL.md` (YAML frontmatter with `name` and `description`).",
    );
    lines.push(
      "<!-- unverified: .agents/skills location from Codex skills docs; not confirmed on the AGENTS.md doc page -->",
    );
    lines.push("");
    lines.push("## How to add a setting");
    lines.push(
      "Uncomment the key in `config.toml` and set its value. Add MCP servers as `[mcp_servers.<name>]` tables.",
    );
    lines.push("");
    lines.push(...formatCavemanSection("##", context.cavemanMode));
    return lines.join("\n");
  }
}
